// "Nghe rồi trả lời" (book listening lessons): mode switch, 4 steps, keyword hints, source segment, saved wrong answers + review.
// Uses a test key and a fake pack (no textbook content). Needs long.mp3 (60 s) in T_DIR or cwd, like nghe-test.cjs.
const { chromium, webkit, devices } = require('playwright');
process.on('unhandledRejection', e => console.log('late rejection (ignored after close):', String(e).slice(0, 80)));
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const S = process.env.T_DIR || process.cwd();
const BASE = 'http://localhost:8765/Pinyin/';
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const KH = crypto.randomBytes(32).toString('hex'), KEY = Buffer.from(KH, 'hex');
const hid = s => crypto.createHash('sha256').update(s + '|' + KH).digest('hex').slice(0, 20);
const enc = b => { const iv = crypto.randomBytes(12), c = crypto.createCipheriv('aes-256-gcm', KEY, iv); return Buffer.concat([iv, c.update(b), c.final(), c.getAuthTag()]); };
const audio = fs.readFileSync(path.join(S, 'long.mp3'));
const zh = ['小明是学生。', '他每天七点起床。', '他喜欢喝茶。', '周末他去公园。', '他觉得很开心。'];
// lines 0-4 at 2..14 s, a long silence, lines 5-9 at 40..52 s (the gap must be skipped when listening)
const lines = zh.concat(zh).map((t, i) => { const s = i < 5 ? 2 + i * 2.4 : 40 + (i - 5) * 2.4; return [s, s + 2.2, t, 'Câu ' + (i + 1)]; });
const Q = (q, a, k, s, f) => ({ q, qv: 'Nghĩa: ' + q, a, av: 'Đáp: ' + a, k, s, ...(f ? { f: 1 } : {}) });
const qa = [{ t: '短文一：小明', vi: 'Bài đọc 1', r: [0, 9], q: [Q('小明是做什么的？', '小明是学生。', ['学生'], [0]), Q('他每天几点起床？', '他每天七点起床。', ['七点', '起床'], [1]), Q('你喜欢喝茶吗？', '我喜欢喝茶。', ['喝茶'], [], 1)], kw: ['学生', '七点', '喝茶'], rt: '小明是学生，他每天七点起床，喜欢喝茶。', rv: 'Tiểu Minh là học sinh.' },
  { t: '短文二：周末', vi: 'Bài đọc 2', r: [3, 4], q: [Q('周末他去哪儿？', '他去公园。', ['公园'], [3])], kw: ['公园'], rt: '周末他去公园。', rv: 'Cuối tuần.' }];
const mk = (id, book, no, t, withQa) => ({ id, book, no, zh: t, vi: 'Tên bài ' + no, file: id + '.mp3', dur: 60, a: hid('a|' + id), size: audio.length + 28, lines, ...(withQa ? { qa } : {}) });
const IDX = { v: 1, lessons: [mk('q3-01', 3, 1, '迎来送往', true), mk('q2-05', 2, 5, '第五课', false)] };
const FILES = { [hid('idx') + '.bin']: enc(Buffer.from(JSON.stringify(IDX))) };
IDX.lessons.forEach(l => FILES[l.a + '.bin'] = enc(audio));
const hz = sel => `[...document.querySelectorAll('${sel} .hz')].map(x=>x.textContent).join('')`;
(async () => {
  const bt = process.env.BT === 'webkit' ? webkit : chromium, name = process.env.BT || 'chromium';
  for (const mobile of (process.env.ONLY === 'desk' ? [false] : [true, false])) {
    const tag = `[${name}${mobile ? ' phone' : ' desktop'}]`;
    const b = await bt.launch(bt === chromium ? { args: ['--autoplay-policy=no-user-gesture-required'] } : {});
    const ctx = await b.newContext(mobile ? { ...devices[bt === webkit ? 'iPhone 13' : 'Pixel 7'] } : { viewport: { width: 1400, height: 900 } });
    await ctx.addInitScript(k => { if (!localStorage.getItem('t.i')) { localStorage.setItem('t.i', '1'); localStorage.setItem('bb.nk', JSON.stringify(k)); } }, KH);
    await ctx.route('**/video/data/nghe/*.bin', r => { const f = r.request().url().split('/').pop(); return FILES[f] ? r.fulfill({ status: 200, body: FILES[f], contentType: 'application/octet-stream' }) : r.fulfill({ status: 404, body: '' }); });
    const pg = await ctx.newPage(); const errs = []; pg.on('pageerror', e => errs.push(String(e)));
    await pg.goto(BASE + 'video/'); await pg.waitForSelector('#tileNghe:not([hidden])', { timeout: 20000 });
    ok(/hỏi đáp/.test(await pg.textContent('#tileNgheSub')), tag + ' home tile mentions hỏi đáp (home stays one tile)');
    await pg.click('#tileNghe'); await pg.waitForSelector('#vNghe:not([hidden])');
    ok(await pg.isVisible('#ngSeg'), tag + ' mode switch on Nghe page');
    await pg.click('[data-ngmode="qa"]');
    ok((await pg.$$eval('#nghe .ng-tag', l => l.map(x => x.textContent))).join() === 'Quyển 3', tag + ' only lessons with questions are listed');
    if (!await pg.$('.ng-book.b3.open')) await pg.click('.ng-book.b3 .ng-h');
    await pg.click('.ng-book.b3 .ng-it'); await pg.waitForSelector('#vQa:not([hidden]) .qa-t');
    ok((await pg.$$('.qa-t')).length === 2, tag + ' texts of the lesson listed');
    await pg.click('.qa-t >> nth=0'); await pg.waitForSelector('#qaP', { timeout: 20000 });
    await pg.click('#qaP'); await pg.waitForTimeout(1200);
    const t1 = await pg.evaluate(() => BM_QA.QAA.el.currentTime);
    ok(t1 > 1.5 && t1 < 4.5, tag + ' plays from the start of the text: ' + t1.toFixed(1));
    await pg.evaluate(() => { BM_QA.QAA.el.currentTime = 14.6; }); await pg.waitForTimeout(1500);
    const t2 = await pg.evaluate(() => BM_QA.QAA.el.currentTime);
    ok(t2 > 39 && t2 < 44, tag + ' long silence inside the text is skipped: ' + t2.toFixed(1));
    await pg.click('[data-qrate="0.8"]'); ok(await pg.evaluate(() => BM_QA.QAA.el.playbackRate) === 0.8, tag + ' slow speed');
    await pg.evaluate(() => { BM_QA.QAA.el.currentTime = 52.2; });
    await pg.waitForFunction(() => BM_QA.QA.heard === 1, null, { timeout: 15000 });
    ok(/Lượt 2/.test(await pg.textContent('#qaPt')), tag + ' round 1 done → round 2');
    await pg.click('#qaGoQ'); await pg.waitForSelector('#qaIn');
    ok(await pg.evaluate(hz('.qa-q')) === '小明是做什么的？', tag + ' question 1 with pinyin text');
    await pg.click('#qaHintB'); ok(await pg.isVisible('#qaHint'), tag + ' Gợi ý shows keywords');
    await pg.fill('#qaIn', '他是学生'); await pg.click('#qaShow'); await pg.waitForSelector('.qa-model');
    ok(/1\/1 ý chính/.test(await pg.textContent('.qa-card')), tag + ' keyword hit counted');
    ok(/小明是学生/.test(await pg.textContent('.qa-src')), tag + ' source sentence shown');
    await pg.click('[data-qsrc]'); await pg.waitForTimeout(700);
    const t3 = await pg.evaluate(() => BM_QA.QAA.el.currentTime); ok(t3 > 1.8 && t3 < 4.5, tag + ' source sentence plays: ' + t3.toFixed(1));
    await pg.click('[data-qok="1"]'); await pg.waitForSelector('#qaIn');
    await pg.click('#qaShow'); await pg.click('[data-qok="0"]'); await pg.waitForSelector('#qaIn');
    ok(await pg.isVisible('.qa-free'), tag + ' free question is marked as not graded');
    await pg.click('#qaShow'); await pg.click('[data-qnext]'); await pg.waitForSelector('.qa-kw');
    await pg.fill('#qaIn', '小明是学生'); await pg.click('#qaRtB');
    ok(/1\/3 từ khóa/.test(await pg.textContent('#qaRt')), tag + ' retell: model shown and keywords counted');
    await pg.click('#qaFin'); await pg.waitForSelector('.qa-sum');
    ok(/1\/2/.test(await pg.textContent('.qa-sum')), tag + ' summary counts graded questions only');
    const st = await pg.evaluate(() => JSON.parse(localStorage.getItem('bb.qa')));
    ok(Object.keys(st.r).join() === 'q3-01|0|1' && st.d['q3-01|0'], tag + ' missed question saved (synced key bb.qa)');
    await pg.evaluate(() => { const s = JSON.parse(localStorage.getItem('bb.qa')); for (const k in s.r) s.r[k].due = '2000-01-01'; localStorage.setItem('bb.qa', JSON.stringify(s)); });
    await pg.click('#qaBk'); await pg.waitForSelector('.qa-t .st.ok'); ok(true, tag + ' text marked done in list');
    await pg.click('[data-qaback]'); await pg.waitForSelector('#vNghe:not([hidden])');
    ok(await pg.isVisible('.qa-due'), tag + ' review banner on Nghe page');
    await pg.click('.qa-due'); await pg.waitForSelector('#qaIn');
    ok(await pg.evaluate(hz('.qa-q')) === '他每天几点起床？', tag + ' review asks the missed question');
    await pg.click('#qaRe'); await pg.waitForTimeout(800);
    const t4 = await pg.evaluate(() => BM_QA.QAA.el.currentTime); ok(t4 > 4 && t4 < 7, tag + ' review replays just that part: ' + t4.toFixed(1));
    await pg.click('#qaShow'); await pg.click('[data-qok="1"]'); await pg.waitForSelector('.qa-sum');
    const r = await pg.evaluate(() => JSON.parse(localStorage.getItem('bb.qa')).r['q3-01|0|1']);
    ok(r && r.ok === 1, tag + ' right once in review → asked again later');
    ok(await pg.evaluate(() => document.documentElement.scrollWidth - innerWidth) <= 0, tag + ' no sideways scroll');
    await pg.click('#qaBk'); await pg.waitForSelector('#vNghe:not([hidden])');
    await pg.click('[data-ngmode="sub"]'); await pg.click('.ng-book.b3 .ng-it'); await pg.waitForSelector('#vLesson:not([hidden])');
    ok(true, tag + ' subtitle mode still opens the normal lesson');
    ok(!errs.length, tag + ' no page errors ' + errs.join(' | '));
    await b.close();
  }
  console.log(fails ? 'FAILS ' + fails : 'ALL PASS'); process.exit(fails ? 1 : 0);
})();
